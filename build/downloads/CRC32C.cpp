uint32_t CRC32C::compute(const void* data, size_t length, uint32_t crc) {
    if (supportsHardwareAcceleration()) {
        return computeHardware(data, length, crc);
    }

    const uint8_t* p = static_cast<const uint8_t*>(data);
    crc = ~crc;

    for (size_t i = 0; i < length; ++i) {
        crc = kCrc32cTable[(crc ^ p[i]) & 0xFF] ^ (crc >> 8);
    }

    return ~crc;
}

uint32_t CRC32C::compute(const std::vector<uint8_t>& data, uint32_t crc) {
    return compute(data.data(), data.size(), crc);
}

uint32_t CRC32C::compute(const std::string& str, uint32_t crc) {
    return compute(str.data(), str.length(), crc);
}

// Hardware acceleration (SSE4.2)
#ifdef _MSC_VER
bool CRC32C::supportsHardwareAcceleration() {
    int cpuInfo[4];
    __cpuid(cpuInfo, 1);
    return (cpuInfo[2] & (1 << 20)) != 0;  // SSE4.2 support
}

uint32_t CRC32C::computeHardware(const void* data, size_t length, uint32_t crc) {
    const uint8_t* p = static_cast<const uint8_t*>(data);
    crc = ~crc;

    // Process 8 bytes at a time
    while (length >= 8) {
        crc = _mm_crc32_u64(crc, *reinterpret_cast<const uint64_t*>(p));
        p += 8;
        length -= 8;
    }

    // Remaining bytes
    while (length--) {
        crc = _mm_crc32_u8(crc, *p++);
    }

    return ~crc;
}
#else
// Fallback for non-MSVC or no SSE4.2
bool CRC32C::supportsHardwareAcceleration() { return false; }
uint32_t CRC32C::computeHardware(const void*, size_t, uint32_t) { return 0; }
#endif